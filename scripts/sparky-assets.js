// Regenerates Sparky's icon files and the mod's copy of his pixels from src/sparky-pixels.js.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rgba, png, ico } from '../src/sparky-pixels.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
writeFileSync(join(root, 'assets', 'sparky.png'), png(16));
writeFileSync(join(root, 'assets', 'sparky.ico'), ico());
writeFileSync(
  join(root, 'plugin', 'hooks', 'sparky-image.ts'),
  `// Generated by scripts/sparky-assets.js: Sparky's 16×16 RGBA pixels, base64.\nexport const SPARKY_RGBA = '${rgba(1).toString('base64')}'\n`,
);
console.log('wrote assets/sparky.png, assets/sparky.ico, plugin/hooks/sparky-image.ts');
