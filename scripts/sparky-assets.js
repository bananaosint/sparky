// Regenerates Sparky's icon files, the terminal backgrounds and the mod's copy of his pixels.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rgba, png, ico, backgroundPng } from '../src/sparky-pixels.js';
import { THEME_NAMES } from '../src/palettes.js';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
writeFileSync(join(root, 'assets', 'sparky.png'), png(16));
writeFileSync(join(root, 'assets', 'sparky.ico'), ico());
for (const theme of THEME_NAMES) writeFileSync(join(root, 'assets', `bg-${theme}.png`), backgroundPng(theme));
writeFileSync(
  join(root, 'plugin', 'hooks', 'sparky-image.ts'),
  `// Generated by scripts/sparky-assets.js: Sparky's 16×16 RGBA pixels, base64.\nexport const SPARKY_RGBA = '${rgba(1).toString('base64')}'\n`,
);
console.log(`wrote assets/sparky.png, sparky.ico, ${THEME_NAMES.map((t) => `bg-${t}.png`).join(', ')}, plugin/hooks/sparky-image.ts`);
